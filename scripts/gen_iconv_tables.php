<?php
// Regenerates src/stdlib/iconv_tables.rs FROM THE REFERENCE:
//
//     /opt/homebrew/bin/php scripts/gen_iconv_tables.php > src/stdlib/iconv_tables.rs && cargo fmt
//
// Every row is what the reference's iconv answered, never typed by hand. The
// reference links the platform libiconv (ICONV_IMPL / ICONV_VERSION, printed in
// the header), whose 8-bit converters substitute a spelling for a character
// the charset lacks even WITHOUT `//TRANSLIT` (`Œ` → `OE` in ISO-8859-1), so
// each 8-bit target gets two tables:
//
//   * FALLBACK — what a plain conversion writes for a character the charset
//     has no byte for;
//   * TRANSLIT — what `//TRANSLIT` adds on top, for characters the plain
//     conversion refuses.
//
// The alias table is every name `iconv -l` lists (the same libiconv) whose
// conversions match one of the charsets phplang implements, fingerprinted on
// probe strings.

// Every codepoint outside ASCII that a spelling was looked for in.
function codepoints(): Generator {
    for ($cp = 0x80; $cp <= 0x2FFFF; $cp++) {
        if ($cp >= 0xD800 && $cp < 0xE000) { continue; }
        yield $cp;
    }
}

// `$b` as a Rust byte-string literal.
function rust_bytes(string $b): string {
    $o = 'b"';
    foreach (str_split($b) as $c) {
        $n = ord($c);
        if ($c === '"' || $c === '\\') { $o .= '\\' . $c; }
        elseif ($n >= 0x20 && $n < 0x7F) { $o .= $c; }
        else { $o .= sprintf('\\x%02x', $n); }
    }
    return $o . '"';
}

// The charsets phplang implements, by the Rust name of their `Charset`.
$charsets = [
    "Utf8" => "UTF-8",
    "Ascii" => "ASCII",
    "Latin1" => "ISO-8859-1",
    "Cp1252" => "CP1252",
    "Latin9" => "ISO-8859-15",
    "Utf16" => "UTF-16",
    "Utf16Be" => "UTF-16BE",
    "Utf16Le" => "UTF-16LE",
    "Utf32" => "UTF-32",
    "Utf32Be" => "UTF-32BE",
    "Utf32Le" => "UTF-32LE",
];

echo "//! GENERATED by `scripts/gen_iconv_tables.php` from ", ICONV_IMPL, " ", ICONV_VERSION,
    " (PHP ", PHP_VERSION, ") — do not edit.\n";

// ── aliases ──
// A charset's fingerprint: what it encodes every probe character to, and what
// it decodes every probe byte string from.
$encode_probes = ["a", "a\u{E9}", "\u{1F600}"];
foreach (codepoints() as $cp) {
    if ($cp <= 0x24F || ($cp >= 0x2000 && $cp <= 0x20CF) || $cp === 0x3042 || $cp === 0xFF21) {
        $encode_probes[] = mb_chr($cp, "UTF-8");
    }
}
$decode_probes = ["a\x00", "\x00a", "a\x00\x00\x00", "\x00\x00\x00a", "\xfe\xff\x00a", "\xff\xfea\x00",
    "\x00\x00\xfe\xff\x00\x00\x00a", "\xff\xfe\x00\x00a\x00\x00\x00", "\xc3\xa9", "\xe2\x82\xac"];
for ($b = 0; $b < 256; $b++) { $decode_probes[] = chr($b); }
$fingerprint = function (string $name) use ($encode_probes, $decode_probes): string {
    $out = [];
    foreach ($encode_probes as $p) { $out[] = @iconv("UTF-8", $name, $p); }
    foreach ($decode_probes as $p) { $out[] = @iconv($name, "UTF-8", $p); }
    return md5(serialize($out));
};
$canon = [];
foreach ($charsets as $rust => $name) { $canon[$fingerprint($name)] = $rust; }
$aliases = [];
foreach (preg_split('/\s+/', trim(shell_exec("/usr/bin/iconv -l"))) as $alias) {
    $alias = strtoupper($alias);
    $rust = $canon[$fingerprint($alias)] ?? null;
    if ($rust !== null) { $aliases[$alias] = $rust; }
}
ksort($aliases, SORT_STRING);
echo "\n/// Every charset name (upper-cased) the reference accepts for a charset phplang\n";
echo "/// implements, sorted for binary search.\n";
echo "pub const ALIASES: &[(&str, super::Charset)] = &[\n";
foreach ($aliases as $alias => $rust) { echo "    (", json_encode((string) $alias), ", super::Charset::$rust),\n"; }
echo "];\n";

// ── 8-bit decode tables ──
foreach (["CP1252" => "CP1252", "ISO-8859-15" => "ISO_8859_15"] as $cs => $const) {
    echo "\n/// The codepoint each byte 0x80..=0xFF of `$cs` stands for (0 = undefined).\n";
    echo "pub const $const: [u32; 128] = [\n";
    for ($b = 0x80; $b <= 0xFF; $b++) {
        $u = @iconv($cs, "UTF-8", chr($b));
        printf("    0x%04X,\n", $u === false || $u === "" ? 0 : mb_ord($u, "UTF-8"));
    }
    echo "];\n";
}

// ── substitutions ──
foreach (["ASCII" => "ASCII", "ISO-8859-1" => "LATIN1", "ISO-8859-15" => "LATIN9", "CP1252" => "CP1252"] as $cs => $const) {
    $fallback = [];
    $translit = [];
    foreach (codepoints() as $cp) {
        $c = mb_chr($cp, "UTF-8");
        $plain = @iconv("UTF-8", $cs, $c);
        if ($plain !== false) {
            if (@iconv($cs, "UTF-8", $plain) !== $c) { $fallback[$cp] = $plain; }
            continue;
        }
        $t = @iconv("UTF-8", "$cs//TRANSLIT", $c);
        if ($t !== false) { $translit[$cp] = $t; }
    }
    foreach (["FALLBACK" => $fallback, "TRANSLIT" => $translit] as $kind => $rows) {
        echo "\n/// `(codepoint, bytes)`: what ", $kind === "FALLBACK"
            ? "a plain conversion to `$cs` writes for a character it has no byte for"
            : "`$cs//TRANSLIT` writes for a character the plain conversion refuses", ".\n";
        echo "pub const {$kind}_$const: &[(u32, &[u8])] = &[\n";
        foreach ($rows as $cp => $b) { printf("    (0x%04X, %s),\n", $cp, rust_bytes($b)); }
        echo "];\n";
    }
}
