<?php
// Regenerates src/internal_interfaces.rs FROM THE REFERENCE:
//
//     /opt/homebrew/bin/php scripts/gen-internal-interfaces.php > src/internal_interfaces.rs && cargo fmt
//
// The order `class_implements` and `ReflectionClass::getInterfaceNames` list
// an internal class's interfaces in is fixed by how ext/* registers the class
// (`zend_class_implements` and the interfaces' own parents), not by a rule a
// user class follows. For every class the PHP-written preludes in src/lib.rs
// stand in for, this records the reference's list; phplang orders the
// interfaces it computes for that class by it.
$root = dirname(__DIR__);
preg_match_all('/^(?:abstract |final |readonly )*class (\w+)/m', file_get_contents("$root/src/lib.rs"), $m);
$classes = array_unique($m[1]);
sort($classes, SORT_STRING | SORT_FLAG_CASE);
echo "//! GENERATED by `scripts/gen-internal-interfaces.php` from PHP ", PHP_VERSION, " — do not edit.\n\n";
echo "/// `(lowercased class, interfaces in the reference's order)` for every prelude\n";
echo "/// class the reference ships, sorted for binary search.\n";
echo "pub const INTERNAL_INTERFACES: &[(&str, &[&str])] = &[\n";
foreach ($classes as $c) {
    if (!class_exists($c)) { continue; }
    $names = (new ReflectionClass($c))->getInterfaceNames();
    if (array_values(class_implements($c)) !== $names) {
        fwrite(STDERR, "$c: class_implements and getInterfaceNames disagree\n");
        exit(1);
    }
    printf("    (%s, &[%s]),\n", json_encode(strtolower($c)), implode(", ", array_map('json_encode', $names)));
}
echo "];\n";
