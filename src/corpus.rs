//! The language corpus: the exact `(name, chapter, signature, description,
//! example)` table that documents every name the current phplang build
//! recognizes.
//!
//! Every entry mirrors real code, and the chapter says which table it came from:
//!   * "Keyword" / "Language construct" / "Operator" / "Cast" — the reserved
//!     words, constructs, and punctuation `src/lexer.rs` tokenizes and
//!     `src/parser.rs` handles.
//!   * "Magic method" — the `__`-prefixed methods the runtime itself invokes
//!     (`src/host.rs`), as opposed to ones a program may merely declare.
//!   * "Predefined constant" — `predefined_constants()` in `src/host.rs`.
//!   * "Prelude class" — the classes `src/lib.rs` compiles from PHP source into
//!     every fresh host (`EXCEPTION_PRELUDE`, `DATETIME_PRELUDE`, `SPL_PRELUDE`).
//!   * "Core library — …" — the core `call_library` match in `src/builtins.rs`.
//!   * every other chapter — one `dispatch` match arm in the module named by the
//!     chapter, from the 26-module chain in `src/stdlib/mod.rs`.
//!
//! Descriptions are written from the implementation, not from the PHP manual.
//! Where phplang diverges from reference PHP 8 — an ignored argument, a bounded
//! approximation, a construct the parser rejects — the description says so. A
//! divergence that goes unstated is a documentation bug.
//!
//! `gen-docs` (`src/bin/gen_docs.rs`) renders this table to `docs/reference.html`
//! and `src/lsp.rs` answers completion and hover from it, so the reference manual
//! never documents a name the runtime does not implement.

